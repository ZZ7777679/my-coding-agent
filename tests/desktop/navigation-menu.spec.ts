/** 三层导航的右键、复制与名称持久化。 Context menus, clipboard and durable names across navigation levels. */
import { mkdir, mkdtemp } from 'node:fs/promises'
import path from 'node:path'
import { electron, expect, test } from './runtime'
import { artifacts, choose, sentinel } from './helpers'

test('sidebar menus expose identity and rename without changing content or selection', async () => {
  test.setTimeout(60000)
  await mkdir(artifacts, { recursive: true })
  const root = await mkdtemp(path.join(artifacts, 'desktop-navigation-'))
  const project = path.join(root, 'project')
  await mkdir(project)
  const env: Record<string, string> = { OPENCODE_API_KEY: sentinel, MY_AGENT_PROJECT_DIR: project }
  for (const [name, value] of Object.entries(process.env))
    if (value !== undefined && !(name in env)) env[name] = value
  delete env.ELECTRON_RUN_AS_NODE
  delete env.ELECTRON_RENDERER_URL
  const app = await electron.launch({
    args: [
      path.resolve(__dirname, '../support/desktop_peer.cjs'),
      '--data-dir',
      path.join(root, 'data')
    ],
    env
  })
  try {
    const page = await app.firstWindow()
    await expect(page.getByTestId('connection-status')).toHaveText('本地后端已连接')
    await choose(app, project)
    await page.getByRole('button', { name: '新建任务 →', exact: true }).click()
    await page.getByLabel('任务名称', { exact: true }).fill('Original task')
    await page.getByLabel('阶段目标', { exact: true }).fill('Original goal')
    await page.getByRole('button', { name: '创建任务与首会话', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Original task', exact: true })).toBeVisible()
    const taskRow = page.locator('.tree-task')
    const taskId = await taskRow.getAttribute('data-task-id')
    expect(taskId).toBeTruthy()
    await taskRow.click({ button: 'right' })
    await page.getByRole('menuitem', { name: '编辑任务…', exact: true }).click()
    await page.getByLabel('阶段目标', { exact: true }).fill('Unsaved goal draft')
    await taskRow.click({ button: 'right' })
    await page.getByRole('menuitem', { name: '重命名', exact: true }).click()
    await page.getByLabel('任务名称', { exact: true }).last().fill('Named task')
    await page.getByRole('button', { name: '保存名称', exact: true }).click()
    await expect(taskRow).toContainText('Named task')
    await expect(page.getByRole('heading', { name: 'Named task', exact: true })).toBeVisible()
    await expect(page.getByLabel('阶段目标', { exact: true })).toHaveValue('Unsaved goal draft')
    await taskRow.click({ button: 'right' })
    await page.getByRole('menuitem', { name: '查看任务信息', exact: true }).click()
    const taskDetails = page.getByRole('dialog', { name: '任务信息' })
    await expect(taskDetails).toContainText(taskId!)
    await expect(taskDetails).toContainText('Original goal')
    await taskDetails.getByRole('button', { name: '关闭', exact: true }).click()
    const projectRow = page.locator('.tree-project')
    await projectRow.focus()
    await page.keyboard.press('Shift+F10')
    await expect(page.getByRole('menu', { name: '项目操作' })).toBeVisible()
    await page.getByRole('menuitem', { name: '复制项目路径', exact: true }).click()
    await expect(page.getByRole('menu').getByRole('status')).toHaveText('已复制项目路径')
    expect(await app.evaluate(({ clipboard }) => clipboard.readText())).toBe(project)
    await page.keyboard.press('Escape')
    await expect(page.getByRole('menu')).toHaveCount(0)
    await projectRow.click({ button: 'right' })
    await page.getByRole('menuitem', { name: '重命名', exact: true }).click()
    await page.getByLabel('项目名称', { exact: true }).fill('Named project')
    await page.getByRole('button', { name: '保存名称', exact: true }).click()
    await expect(projectRow).toContainText('Named project')
    await projectRow.click({ button: 'right' })
    await page.getByRole('menuitem', { name: '查看项目信息', exact: true }).click()
    const projectDetails = page.getByRole('dialog', { name: '项目信息' })
    await expect(projectDetails).toContainText(project)
    await projectDetails.getByRole('button', { name: '关闭', exact: true }).click()
    await page.getByRole('button', { name: '打开 / 补齐首会话', exact: true }).click()
    const sessionRow = page.locator('.tree-session').first()
    const sid = await sessionRow.getAttribute('data-session-id')
    expect(sid).toBeTruthy()
    await sessionRow.click({ button: 'right' })
    await page.getByRole('menuitem', { name: '查看会话信息', exact: true }).click()
    const details = page.getByRole('dialog', { name: '会话信息' })
    await expect(details).toContainText(sid!)
    await expect(details).toContainText(taskId!)
    await expect(details).toContainText('Named task')
    await expect(details).toContainText('Named project')
    await details.getByRole('button', { name: '复制全部信息', exact: true }).click()
    await expect(details.getByRole('status')).toHaveText('已复制全部信息')
    expect(await app.evaluate(({ clipboard }) => clipboard.readText())).toContain(sid!)
    await details.getByRole('button', { name: '重命名', exact: true }).click()
    await page.getByLabel('会话名称', { exact: true }).fill('Implement counter')
    await page.getByRole('button', { name: '保存名称', exact: true }).click()
    await expect(sessionRow).toContainText('Implement counter')
    await page.reload()
    await expect(page.getByTestId('connection-status')).toHaveText('本地后端已连接')
    await expect(projectRow).toContainText('Named project')
    await page.getByRole('button', { name: '展开项目 Named project', exact: true }).click()
    await expect(taskRow).toContainText('Named task')
    await page.getByRole('button', { name: '展开任务 Named task', exact: true }).click()
    await expect(sessionRow).toContainText('Implement counter')
    await sessionRow.click({ button: 'right' })
    await page.getByRole('menuitem', { name: '复制 ID', exact: true }).click()
    await expect(page.getByRole('menu').getByRole('status')).toHaveText('已复制会话 ID')
    expect(await app.evaluate(({ clipboard }) => clipboard.readText())).toBe(sid)
    await page.getByRole('menuitem', { name: '查看会话信息', exact: true }).click()
    await page.screenshot({ path: path.join(root, 'session-information.png') })
    await page.keyboard.press('Escape')
    await expect(page.getByRole('dialog')).toHaveCount(0)
    await sessionRow.click({ button: 'right' })
    await page.getByRole('menuitem', { name: '打开所属任务', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Named task', exact: true })).toBeVisible()
  } finally {
    await app.close()
  }
})
